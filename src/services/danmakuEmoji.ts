/** 匹配 `[码名]`：方括号内 1–10 个非括号字符（与红果/微信系码的实际长度上限一致）。 */
const EMOTE_PATTERN = /\[([^\[\]]{1,10})\]/g;

/** 把文本里的已知表情码替换成 emoji；未收录的码原样保留。 */
export function applyEmotes(text: string): string {
  if (!text || text.indexOf('[') < 0) return text;
  return text.replace(EMOTE_PATTERN, (whole, code: string) => {
    const emoji = EMOTE_MAP[code];
    return emoji ?? whole;
  });
}

